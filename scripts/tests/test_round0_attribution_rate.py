def ledger(requirements=7, unattributed=2) -> str:
    """The round-0 ledger line, as the skill tells the auditor to write it."""
    return (f"## Round 0\nround 0 · requirements: {requirements} "
            f"(unattributed: {unattributed})\n")


def assistant(text, ts=PRE_TS) -> dict:
    return {"type": "assistant", "timestamp": ts,
            "message": {"role": "assistant",
                        "content": [{"type": "text", "text": text}]}}


def tool_result(text, ts=PRE_TS) -> dict:
    return {"type": "user", "timestamp": ts,
            "message": {"role": "user",
                        "content": [{"type": "tool_result", "tool_use_id": "t1",
                                     "content": text}]}}


def user_text(text, ts=PRE_TS) -> dict:
    return {"type": "user", "timestamp": ts,
            "message": {"role": "user",
                        "content": [{"type": "text", "text": text}]}}


def brief(r0, oa, shape, tmp_path) -> str:
    """A real `render()` output — the strings the instrument matches on.

    Built from the script's own probe matrix so the fixture cannot drift away
    from what production emits: `answered`, `unmeasured`, `dropped`, `no-source`.
    """
    probes = r0.renderer_probes(oa, tmp_path / "no-such-projects-root")
    return probes[shape]


def write(path: Path, records) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(r) for r in records) + "\n")
    return path


def corpus_with(tmp_path, sessions: dict) -> Path:
    """sessions: {relative transcript path -> [records]} under a fresh corpus."""
    root = tmp_path / "corpus"
    for rel, records in sessions.items():
        write(root / rel, records)
    root.mkdir(parents=True, exist_ok=True)
    return root


def run(r0, argv) -> tuple[int, str]:
    """-> (exit code, stdout text). `fail()` exits, so SystemExit is caught.

    The code is asserted to be an INT: this script exits only with its own
    documented codes, and a `str`/`None` exit would otherwise compare unequal to
    every expected code and read as an ordinary wrong-code failure.
    """
    buf = io.StringIO()
    try:
        code = r0.main(argv, out_stream=buf)
    except SystemExit as e:
        code = e.code
    assert isinstance(code, int), f"non-int exit {code!r}\n{buf.getvalue()}"
    return code, buf.getvalue()


def rates(r0, corpus, tmp_path, extra=()) -> tuple[int, str, dict]:
    """Run over `corpus` and return (code, stdout, the JSON bucket report).

    🔴 THE REPORT'S EXISTENCE IS ASSERTED HERE, never returned as `None`. A
    `None` payload would turn every caller's `payload["buckets"]…` arithmetic
    into a `TypeError` far from the cause — and a caller that checked only
    truthiness would sail past a run that produced no report at all, which is
    the vacuous-pass shape. A missing file is this helper's own failure, with the
    run's output attached.
    """
    out = tmp_path / "rates.json"
    code, text = run(r0, ["--corpus", str(corpus), "--cut-iso", CUT_ISO,
                          "--json", str(out), *extra])
    assert out.exists(), (
        f"the run wrote no --json report (exit {code}), so there are no buckets "
        f"to assert on. Its output was:\n{text}")
    payload = json.loads(out.read_text())
    assert isinstance(payload, dict) and "buckets" in payload, payload
    return code, text, payload


