def test_every_exit_code_constant_is_documented_in_the_docstring(r0):
    """invariant: a code nobody documented is a code a reader will guess at.
    Two-way-ish: each constant's NUMBER must appear in the `Exit codes:` prose,
    and the prose is the only place their meanings live."""
    doc = r0.__doc__ or ""
    codes = doc.split("Exit codes:", 1)
    assert len(codes) == 2, "the docstring has no `Exit codes:` section"
    legend = codes[1]
    for name in ("EXIT_OK", "EXIT_USAGE", "EXIT_CONTROL", "EXIT_NOTHING_WALKED",
                 "EXIT_PIN", "EXIT_NOT_MEASURABLE"):
        value = getattr(r0, name)
        assert f"{value} " in legend or f"{value}·" in legend, (
            f"{name}={value} is not documented in the Exit codes legend")


