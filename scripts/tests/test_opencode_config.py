def test_no_agent_reopens_the_bash_wildcard_with_allow():
    """🔴 The k8s regression, structurally.

    An agent-level `bash: {"*": allow}` is appended AFTER the entire global
    block, so last-match-wins makes it nullify every global deny at a stroke.
    Measured on 1.18.4: it landed at index 74 after all 30 global rules and left
    only the 4 agent-local rules standing — `git stash`, `git reset --hard`,
    `rm -rf ~…`, `sops -d`, `nixos-rebuild` and `home-manager switch` were all
    plain ALLOW on the k8s agent.

    An agent block may only ever TIGHTEN. The global `"*": allow` already keeps
    bash present in the tool map, so re-stating it buys nothing and costs
    everything.
    """
    offenders = []
    for name in sorted(EXPECTED_AGENTS):
        bash = agent_permission(name).get("bash")
        if isinstance(bash, dict) and bash.get("*") == "allow":
            offenders.append(name)
    assert not offenders, (
        f"agent(s) {offenders} declare `bash: {{'*': allow}}`. That is appended "
        f"AFTER the global block and NULLIFIES every global deny/ask. Drop it — "
        f"the global wildcard already enables bash."
    )


def test_bash_permission_wildcard_is_first():
    """`"*": "allow"` must be the FIRST key of the bash block.

    NOTE this is an INVARIANT GUARD, not regression coverage: it is exactly the
    assertion that passed under both mutations that mattered. It is kept because
    it localises the failure, but the real protection is the effective-action
    tests above.
    """
    bash = load_config()["permission"]["bash"]
    keys = list(bash)
    assert keys[0] == "*", (
        f"first key of the bash permission block is {keys[0]!r}, not '*'."
    )
    assert bash["*"] == "allow"


def test_no_allow_rule_follows_the_wildcard():
    """🔴 The missing assertion that makes a trailing `"git *": "allow"` fail.

    A single broad `allow` appended anywhere after index 0 resurrects every deny
    above it. Nothing but the leading wildcard may be an `allow`.
    """
    bash = load_config()["permission"]["bash"]
    offenders = [k for k, v in list(bash.items())[1:] if v == "allow"]
    assert not offenders, (
        f"`allow` rules after the leading wildcard: {offenders}. opencode is "
        f"LAST-MATCH-WINS, so each of these re-opens every deny/ask above it."
    )


def test_all_asks_precede_all_denies():
    """Deny-last is what makes a narrow deny beat a broad ask.

    `*talosctl reset*: deny` only wins over `*talosctl*: ask` because it comes
    later. Interleaving them, or sorting the block, silently downgrades denies.
    """
    items = list(load_config()["permission"]["bash"].items())[1:]
    last_ask = max((i for i, (_, v) in enumerate(items) if v == "ask"), default=-1)
    first_deny = min((i for i, (_, v) in enumerate(items) if v == "deny"), default=len(items))
    assert first_deny > last_ask, (
        f"a `deny` appears at index {first_deny} before an `ask` at {last_ask}. "
        f"All asks must precede all denies, or a broad ask can override a "
        f"narrow deny."
    )


def test_every_dangerous_pattern_is_prefix_tolerant():
    """🔴 Every deny/ask must be leading-`*`.

    opencode matches a command node's FULL text, so a bare `"git stash*"` misses
    `FOO=1 git stash`, `sudo -n git stash` and `git -C /tmp stash` — measured,
    all three ALLOWED. A handful of anchored patterns are legitimate (a bare
    command name that cannot be meaningfully prefixed); they are listed
    explicitly so adding a new anchored pattern is a deliberate act.
    """
    allowed_anchored = {"*", "sudo*", "dd *"}
    offenders = [
        k for k, v in load_config()["permission"]["bash"].items()
        if v != "allow" and not k.startswith("*") and k not in allowed_anchored
    ]
    assert not offenders, (
        f"bash patterns that are not prefix-tolerant: {offenders}. Prefix each "
        f"with `*` or add it to `allowed_anchored` with a reason."
    )


