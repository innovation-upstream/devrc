r"""Tests for the home-manager-managed opencode configuration.

WHAT IS UNDER TEST (see scripts/opencode/README.md for the measurements):

  1. The GENERATED ~/.config/opencode/AGENTS.md. `nix/home.nix` builds it by
     CONCATENATING claude/PRINCIPLES.md + claude/RULES.md +
     claude/opencode-addendum.md at switch time. It has to be a concatenation
     because opencode does NOT expand `@`-imports in AGENTS.md/CLAUDE.md
     (measured on v1.18.4 with an all-tools-denied agent, so no file read was
     possible: an imported passphrase returned NONE, the same content inline
     returned verbatim). ~/.claude/CLAUDE.md is ~1.5 KB of `@PRINCIPLES.md` +
     `@RULES.md` import lines, so if opencode read THAT it would receive none of
     the 32 KB of actual rules. These tests are the regression guard for that
     whole point: they assert the rules TEXT is present, not merely that a file
     exists.

  2. 🔴 The EFFECTIVE RESOLVED PERMISSION for a set of dangerous commands, on
     EVERY agent. This is the section that matters, and it is deliberately NOT
     a restatement of the file's keys.

     A previous version of this file asserted only key ORDER, and was vacuous
     against the two mutations that actually break the config:
       * appending a trailing `"git *": "allow"` (resurrects every git deny)
         — 82 passed;
       * sorting the bash keys alphabetically — 82 passed, because `"*"` (0x2A)
         sorts to the front, so the "wildcard is first" assertion still held
         while a broad `ask` overtook the narrow `deny` it was meant to lose to.
     Both are pinned by `effective_bash_action` below, which REIMPLEMENTS
     opencode's resolver and asserts the outcome.

  3. The resolver model itself. opencode 1.18.4 resolves a permission by
     `findLast` over a FLAT ORDERED array (built-in defaults, then agent rules,
     then user config — later wins), matching with a hand-rolled glob→regex:

         pattern.replace(/[.+^${}()|[\]\\]/g,"\\$&").replace(/\*/g,".*")
                .replace(/\?/g,".")   ->   new RegExp("^"+p+"$","s")

     so `*` is an unrestricted `.*` (dotAll) that CROSSES spaces, `/` and `-`.
     `wildcard_match` below is a faithful port, including the special case where
     a pattern ending in `" *"` also matches without the trailing part.

     VALIDATED against the real engine, not just read off the source: the same
     expectations were replayed through `opencode debug agent <a> --tool bash`
     (which performs a genuine permission check) and all 18 deny cases and 3
     allow cases agreed. NOTE `ask` is auto-approved in that non-interactive
     mode and is indistinguishable from `allow` there, which is why the `ask`
     rows are pinned by this model rather than by execution.

  4. The `shell.env` handles. Generated by nix from nix/agent-handles.nix, the
     single source of truth shared with programs/zsh.

  5. The subagent definitions parse as YAML frontmatter + body, and — 🔴 — that
     no agent re-opens the bash wildcard.

Mostly hermetic: pure file reads under the repo. Two tests shell out to
`nix-instantiate --eval` to pin the generated handle VALUES; they FAIL (not
skip) if nix is absent, because a silent skip there is how a wrong path ships.

    run:  python -m pytest scripts/tests/test_opencode_config.py -q
"""

