@pytest.mark.parametrize(
    "text,pattern,expected",
    [
        # `*` must cross spaces, `/` and `-` — the whole basis of the F3 fix.
        ("git -C /tmp stash", "*git*stash*", True),
        ("FOO=1 git stash", "*git*stash*", True),
        ("sudo -n git stash", "*git*stash*", True),
        ("git stash", "*git*stash*", True),
        # …and the bare form must NOT, which is the bug being fixed.
        ("git -C /tmp stash", "git stash*", False),
        ("FOO=1 git stash", "git stash*", False),
        ("git status", "*git*stash*", False),
        # the " *" suffix special case
        ("rg", "rg *", True),
        ("rg foo", "rg *", True),
        # anchoring
        ("mkfs.ext4 /dev/sda", "*mkfs*", True),
        ("ls -la", "*mkfs*", False),
    ],
)
def test_wildcard_match_models_the_real_engine(text, pattern, expected):
    """MUTATION CONTROL for the resolver model.

    Every row was replayed through the real engine (`opencode debug agent
    --tool bash`, or the extracted `Wildcard.match` run under node). If this
    port drifts from opencode's semantics, every effective-action assertion
    below becomes a fiction, so it is pinned independently.
    """
    assert wildcard_match(text, pattern) is expected


def test_effective_action_model_is_last_match_wins():
    """Negative control for the resolver: a later broad rule MUST beat an
    earlier narrow one. If this ever reports first-match-wins, every
    effective-action test below is meaningless."""
    rules = [("*", "allow"), ("git stash*", "deny"), ("git *", "allow")]
    action = "ask"
    for pat, act in rules:
        if wildcard_match("git stash", pat):
            action = act
    assert action == "allow", "model is not last-match-wins"


